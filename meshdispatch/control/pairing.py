def device_enroller_from_manager(manager: Any) -> Callable[[str, str], str]:
    """Build an ``(principal, device_name) -> device_id`` enroller from auth.

    Enrolment goes through :meth:`~meshdispatch.auth.AuthManager.enroll_device`
    and is then confirmed so the freshly paired device is immediately usable.
    """

    def enroll(principal: str, device_name: str) -> str:
        device_id = manager.enroll_device(principal, device_name=device_name)
        manager.confirm_device(device_id, approver_principal=principal)
        return device_id

    return enroll


def device_lister_from_manager(manager: Any) -> Callable[..., list[dict[str, Any]]]:
    """Build a device lister that reads auth's device store."""

    def list_devices(principal: str | None = None) -> list[dict[str, Any]]:
        return manager.store.list_devices(principal)

    return list_devices


def device_revoker_from_manager(manager: Any) -> Callable[[str], bool]:
    """Build a device revoker that un-confirms a device in auth's store.

    Delegates to :meth:`~meshdispatch.auth.AuthManager.revoke_device`; auth's
    device layer refuses unconfirmed devices, so this deauthorises the device
    without deleting the audit trail.
    """

    def revoke(device_id: str) -> bool:
        revoke_device = getattr(manager, "revoke_device", None)
        if callable(revoke_device):
            return bool(revoke_device(device_id))
        # Backwards compatible with managers that predate ``revoke_device``.
        rec = manager.store.get_device(device_id)
        if rec is None:
            return False
        rec["confirmed"] = False
        rec["confirmed_at"] = None
        rec["confirmed_by"] = None
        manager.store.set_device(device_id, rec)
        return True

    return revoke


